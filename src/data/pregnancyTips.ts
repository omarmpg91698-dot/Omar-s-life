const DAY_MS = 86_400_000;

export function daysBetween(fromIso: string, toIso: string): number {
  const from = new Date(fromIso + 'T00:00:00');
  const to = new Date(toIso + 'T00:00:00');
  return Math.round((to.getTime() - from.getTime()) / DAY_MS);
}

// Pregnancy week (1-42) from the due date, same formula as the Baby section:
// ~280 days of pregnancy, week = elapsed days / 7 + 1.
export function pregnancyWeekFor(dueDateIso: string, todayIso: string): number {
  const daysLeft = daysBetween(todayIso, dueDateIso);
  return Math.min(42, Math.max(1, Math.floor((280 - daysLeft) / 7) + 1));
}

export function tipForWeek(week: number): string {
  return PREGNANCY_TIPS[Math.min(40, Math.max(1, week)) - 1];
}
